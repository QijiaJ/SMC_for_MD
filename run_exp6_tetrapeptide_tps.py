def encode_sequence_features(sequence):
    seq = str(sequence).upper()
    out = np.zeros((MAX_RESIDUES, len(AA_ALPHABET)), dtype=np.float64)
    for idx, aa in enumerate(seq[:MAX_RESIDUES]):
        aa_idx = AA_TO_INDEX.get(aa)
        if aa_idx is not None:
            out[idx, aa_idx] = 1.0
    return out.reshape(-1)


def peptide_conditioning_sequence(peptide):
    name = peptide.get("name")
    if name is not None:
        return str(name).upper()
    sequence = peptide.get("sequence")
    if sequence is not None:
        return str(sequence).upper()
    return ""


def prepare_peptide_features(peptide):
    features = np.asarray(peptide["features"], dtype=np.float64)
    feature_mask = None
    if peptide.get("mask") is not None:
        feature_mask = np.repeat(np.asarray(peptide["mask"], dtype=np.float64).reshape(-1), 2)
        features = features * feature_mask[None, :]
    return features, feature_mask


def _clone_model_state(model):
    return OrderedDict((key, value.detach().cpu().clone()) for key, value in model.state_dict().items())


def _restore_model_state(model, state):
    model.load_state_dict(state)


def _model_parameters_are_finite(model):
    return all(torch.isfinite(param).all().item() for param in model.parameters())


def _reset_optimizer_state(optimizer):
    optimizer.state.clear()


def _halve_optimizer_lr(optimizer, min_lr=1e-5):
    new_lr = None
    for group in optimizer.param_groups:
        group["lr"] = max(float(group["lr"]) * 0.5, float(min_lr))
        new_lr = group["lr"]
    return new_lr


