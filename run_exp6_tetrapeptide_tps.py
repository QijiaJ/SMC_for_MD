"""
Tetrapeptide transition-path-sampling experiment with a shared sequence-conditioned
proposal model and two Take 3 adaptation modes on held-out peptides.

This runner assumes preprocessed per-peptide torsion files produced by
`prep_tetrapeptide_data.py` or equivalent npz files with:
  - angles: (n_frames, 4, 7) or (n_frames, n_torsions)
or
  - features: (n_frames, 2 * n_torsions)

It uses:
  - a leave-one-out shared proposal model trained on the other loaded peptides
    with short-history conditioning (current frame, two previous frames, and
    the corresponding deltas)
  - a reference 10-state MSM built from the held-out peptide trajectory
  - the rarest non-zero flux start/end state pair, following the MDGen paper
  - reward-only endpoint conditioning toward the chosen end state
  - two twist variants on the held-out peptide:
      * Oracle: trained from real held-out peptide windows
      * Self: trained from unconditional windows generated by the shared proposal itself

Metrics:
  - JSD of visited states vs conditioned reference MSM paths
  - valid path rate
  - average path probability under the reference MSM
"""

