def _reshape_history_array(x):
    x = np.asarray(x, dtype=np.float64)
    if x.ndim == 1:
        return x.reshape(1, -1)
    return x.reshape(len(x), -1)


def build_history_context(x_curr, prev_frames=None, history_frames=2):
    x_curr = np.asarray(x_curr, dtype=np.float64)
    if history_frames < 1:
        raise ValueError("history_frames must be at least 1.")
    x_curr = _reshape_history_array(x_curr)

    prev_frames = [] if prev_frames is None else list(prev_frames)
    history = [x_curr]
    last = x_curr
    for idx in range(history_frames - 1):
        frame = prev_frames[idx] if idx < len(prev_frames) else last
        if frame is None:
            arr = last
        else:
            arr = _reshape_history_array(frame)
            if len(arr) == 1 and len(x_curr) > 1:
                arr = np.tile(arr, (len(x_curr), 1))
            elif len(arr) != len(x_curr):
                raise ValueError("Previous history frames must broadcast to x_curr in build_history_context.")
        history.append(arr)
        last = arr

    deltas = [history[idx] - history[idx + 1] for idx in range(len(history) - 1)]
    return np.concatenate(history + deltas, axis=-1)


def train_sequence_conditional_score(context_data, x_next_data, seq_data, dim, context_dim, seq_dim,
                                     n_epochs=3000, batch_size=256, lr=1e-3, S_max=2.0,
                                     hidden_dim=128, n_layers=4, device="cpu", verbose=True):
    context_data = np.nan_to_num(np.asarray(context_data, dtype=np.float64).reshape(-1, context_dim), nan=0.0, posinf=3.0, neginf=-3.0)
    x_next_data = np.nan_to_num(np.asarray(x_next_data, dtype=np.float64).reshape(-1, dim), nan=0.0, posinf=2.0, neginf=-2.0)
    seq_data = np.nan_to_num(np.asarray(seq_data, dtype=np.float64).reshape(-1, seq_dim), nan=0.0, posinf=1.0, neginf=0.0)
    if not (len(context_data) == len(x_next_data) == len(seq_data)):
        raise ValueError("context_data, x_next_data, and seq_data must have the same number of rows.")

    model = ScoreNet(input_dim=dim + context_dim + seq_dim, output_dim=dim,
                     hidden_dim=hidden_dim, n_layers=n_layers).to(device)
    optimizer = optim.Adam(model.parameters(), lr=lr)
    scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, n_epochs)
    last_good_state = _clone_model_state(model)

    xt = torch.tensor(context_data, dtype=torch.float32, device=device)
    xtp1 = torch.tensor(x_next_data, dtype=torch.float32, device=device)
    seq_t = torch.tensor(seq_data, dtype=torch.float32, device=device)
    n = len(xt)
    losses = []

    for epoch in range(n_epochs):
        idx = torch.randint(0, n, (batch_size,), device=device)
        context_batch = xt[idx]
        x0 = xtp1[idx]
        seq_batch = seq_t[idx]

        s = torch.rand(batch_size, device=device) * (S_max - 0.01) + 0.01
        alpha = torch.exp(-s / 2.0).unsqueeze(-1)
        sigma = torch.sqrt(torch.clamp(1.0 - torch.exp(-s), min=1e-10)).unsqueeze(-1)
        eps = torch.randn_like(x0)
        xs = alpha * x0 + sigma * eps

        target = torch.clamp(torch.nan_to_num(-eps / sigma, nan=0.0, posinf=25.0, neginf=-25.0), -25.0, 25.0)
        inp = torch.clamp(torch.nan_to_num(torch.cat([xs, context_batch, seq_batch], dim=-1), nan=0.0, posinf=4.0, neginf=-4.0), -4.0, 4.0)
        score_pred = torch.clamp(torch.nan_to_num(model(inp, s), nan=0.0, posinf=25.0, neginf=-25.0), -25.0, 25.0)

        weight = sigma.squeeze(-1) ** 2
        per_sample = torch.sum((score_pred - target) ** 2, dim=-1)
        loss = torch.mean(weight * per_sample)
        if not torch.isfinite(loss):
            restored_lr = _halve_optimizer_lr(optimizer)
            _restore_model_state(model, last_good_state)
            _reset_optimizer_state(optimizer)
            if verbose:
                print(f"    [Shared Conditional] epoch {epoch+1}/{n_epochs}: non-finite loss, restoring last good state and lowering lr to {restored_lr:.2e}")
            continue

        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        grad_norm = torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        if not torch.isfinite(grad_norm):
            restored_lr = _halve_optimizer_lr(optimizer)
            _restore_model_state(model, last_good_state)
            _reset_optimizer_state(optimizer)
            optimizer.zero_grad(set_to_none=True)
            if verbose:
                print(f"    [Shared Conditional] epoch {epoch+1}/{n_epochs}: non-finite gradient, restoring last good state and lowering lr to {restored_lr:.2e}")
            continue
        optimizer.step()
        if not _model_parameters_are_finite(model):
            restored_lr = _halve_optimizer_lr(optimizer)
            _restore_model_state(model, last_good_state)
            _reset_optimizer_state(optimizer)
            if verbose:
                print(f"    [Shared Conditional] epoch {epoch+1}/{n_epochs}: non-finite parameters, restoring last good state and lowering lr to {restored_lr:.2e}")
            continue
        scheduler.step()
        last_good_state = _clone_model_state(model)
        losses.append(float(loss.item()))

        if verbose and (epoch + 1) % 500 == 0:
            print(f"    [Shared Conditional] epoch {epoch+1}/{n_epochs}: loss={loss.item():.4f}")

    model.eval()
    return model, losses


def _allocate_balanced_counts(avail_counts, total_budget):
    avail = np.asarray(avail_counts, dtype=np.int64)
    total_budget = int(min(max(total_budget, 0), int(np.sum(avail))))
    if total_budget <= 0 or len(avail) == 0:
        return np.zeros(len(avail), dtype=np.int64)

    counts = np.minimum(avail, total_budget // len(avail))
    remaining = total_budget - int(np.sum(counts))
    while remaining > 0:
        candidates = np.where(counts < avail)[0]
        if len(candidates) == 0:
            break
        for idx in candidates:
            if remaining <= 0:
                break
            counts[idx] += 1
            remaining -= 1
    return counts


def collect_shared_transition_pairs(peptides, max_pairs, rng, balanced=True, history_frames=2):
    pair_data = []
    dim = None
    context_dim = None

    for peptide in peptides:
        features, _ = prepare_peptide_features(peptide)
        if len(features) < 2:
            continue
        if dim is None:
            dim = features.shape[1]
        elif features.shape[1] != dim:
            raise ValueError("All peptides must share the same feature dimension for transferable score training.")
        pair_curr = features[:-1]
        pair_history = []
        pair_indices = np.arange(len(pair_curr))
        for lag in range(1, history_frames):
            pair_history.append(pair_curr[np.maximum(pair_indices - lag, 0)])
        pair_x = build_history_context(pair_curr, prev_frames=pair_history, history_frames=history_frames)
        pair_y = features[1:]
        if context_dim is None:
            context_dim = pair_x.shape[1]
        elif pair_x.shape[1] != context_dim:
            raise ValueError("All peptides must share the same history-context dimension.")
        seq_feat = encode_sequence_features(peptide_conditioning_sequence(peptide))
        seq_data = np.tile(seq_feat[None, :], (len(features) - 1, 1))
        pair_data.append({
            "name": peptide["name"],
            "pair_x": pair_x,
            "pair_y": pair_y,
            "seq": seq_data,
        })

    if not pair_data:
        raise ValueError("No valid transition pairs were found in the training peptide set.")

    if max_pairs is None:
        counts = np.asarray([len(item["pair_x"]) for item in pair_data], dtype=np.int64)
    elif balanced:
        counts = _allocate_balanced_counts([len(item["pair_x"]) for item in pair_data], max_pairs)
    else:
        counts = np.asarray([len(item["pair_x"]) for item in pair_data], dtype=np.int64)

    pair_x_parts = []
    pair_y_parts = []
    seq_parts = []
    sampling_counts = {}
    for item, keep_count in zip(pair_data, counts):
        if max_pairs is None:
            keep_count = len(item["pair_x"])
        keep_count = int(min(keep_count, len(item["pair_x"])))
        if keep_count <= 0:
            continue
        if keep_count < len(item["pair_x"]):
            idx = rng.choice(len(item["pair_x"]), size=keep_count, replace=False)
            pair_x_parts.append(item["pair_x"][idx])
            pair_y_parts.append(item["pair_y"][idx])
            seq_parts.append(item["seq"][idx])
        else:
            pair_x_parts.append(item["pair_x"])
            pair_y_parts.append(item["pair_y"])
            seq_parts.append(item["seq"])
        sampling_counts[item["name"]] = keep_count

    pair_x = np.concatenate(pair_x_parts, axis=0)
    pair_y = np.concatenate(pair_y_parts, axis=0)
    seq_data = np.concatenate(seq_parts, axis=0)

    if max_pairs is not None and (not balanced) and len(pair_x) > max_pairs:
        idx = rng.choice(len(pair_x), size=max_pairs, replace=False)
        pair_x = pair_x[idx]
        pair_y = pair_y[idx]
        seq_data = seq_data[idx]
        sampling_counts = {"global_subsample": int(len(pair_x))}

    meta = {
        "balanced": bool(balanced),
        "per_peptide_counts": sampling_counts,
        "total_pairs": int(len(pair_x)),
    }
    return pair_x, pair_y, seq_data, dim, context_dim, meta


def choose_test_peptides(peptides, seed, test_peptide=None, max_test_peptides=None):
    peptide_names = [peptide["name"] for peptide in peptides]
    if test_peptide is not None:
        if test_peptide not in peptide_names:
            raise ValueError(f"Requested held-out peptide {test_peptide} was not found in the loaded peptide set.")
        return [test_peptide]

    if max_test_peptides is None or len(peptide_names) <= max_test_peptides:
        return peptide_names

    rng = np.random.default_rng(seed)
    idx = rng.choice(len(peptide_names), size=max_test_peptides, replace=False)
    chosen = {peptide_names[i] for i in idx}
    return [name for name in peptide_names if name in chosen]


def conditional_score_eval(o_score, x_batch, s, context_batch, seq_batch=None):
    dim = o_score.dim
    x_arr = np.asarray(x_batch, dtype=np.float64).reshape(-1, dim)
    context_arr = np.asarray(context_batch, dtype=np.float64)
    if context_arr.ndim == 1:
        context_arr = context_arr.reshape(1, o_score.context_dim)
    else:
        context_arr = context_arr.reshape(-1, o_score.context_dim)
    if len(context_arr) == 1 and len(x_arr) > 1:
        context_arr = np.tile(context_arr, (len(x_arr), 1))
    elif len(context_arr) != len(x_arr):
        raise ValueError("x_batch and context_batch must have matching batch sizes.")

    inputs = [x_arr, context_arr]
    if getattr(o_score, "seq_dim", 0):
        if seq_batch is None:
            raise ValueError("Sequence-conditioned score evaluation requires seq_batch.")
        seq_arr = np.asarray(seq_batch, dtype=np.float64)
        if seq_arr.ndim == 1:
            seq_arr = seq_arr.reshape(1, o_score.seq_dim)
        else:
            seq_arr = seq_arr.reshape(-1, o_score.seq_dim)
        if len(seq_arr) == 1 and len(x_arr) > 1:
            seq_arr = np.tile(seq_arr, (len(x_arr), 1))
        elif len(seq_arr) != len(x_arr):
            raise ValueError("seq_batch must have matching batch size.")
        inputs.append(seq_arr)

    with torch.no_grad():
        inp = torch.tensor(
            np.concatenate(inputs, axis=-1),
            dtype=torch.float32,
            device=o_score.device,
        )
        st = torch.full((len(x_arr),), float(s), dtype=torch.float32, device=o_score.device)
        out = o_score.model(inp, st).cpu().numpy()
    return np.clip(out, -o_score.clip, o_score.clip)


def _as_float_tensor(x, device):
    if isinstance(x, torch.Tensor):
        return x.to(device=device, dtype=torch.float32)
    return torch.as_tensor(x, dtype=torch.float32, device=device)


def _build_history_context_torch(x_curr, prev_frames, history_frames, device):
    if history_frames < 1:
        raise ValueError("history_frames must be at least 1.")
    history = [x_curr]
    last = x_curr
    prev_frames = [] if prev_frames is None else list(prev_frames)
    for idx in range(history_frames - 1):
        frame = prev_frames[idx] if idx < len(prev_frames) else last
        if frame is None:
            arr = last
        else:
            arr = _as_float_tensor(frame, device)
            if arr.ndim == 1:
                arr = arr.reshape(1, -1)
            else:
                arr = arr.reshape(arr.shape[0], -1)
            if arr.shape[0] == 1 and x_curr.shape[0] > 1:
                arr = arr.repeat(x_curr.shape[0], 1)
            elif arr.shape[0] != x_curr.shape[0]:
                raise ValueError("History frames must broadcast to x_cond in reverse_step.")
        history.append(arr)
        last = arr
    deltas = [history[idx] - history[idx + 1] for idx in range(len(history) - 1)]
    return torch.cat(history + deltas, dim=-1)


def reverse_step(o_score, x_cond, n_samples, s_max, n_steps, prev_frames=None, feature_mask=None, seq_feature=None, history_frames=2):
    device = o_score.device
    x_cond_t = _as_float_tensor(x_cond, device)
    if x_cond_t.ndim == 1:
        x_cond_t = x_cond_t.reshape(1, -1)
    else:
        x_cond_t = x_cond_t.reshape(x_cond_t.shape[0], -1)
    dim = x_cond_t.shape[1]
    n_cond = x_cond_t.shape[0]

    context_t = _build_history_context_torch(
        x_cond_t,
        prev_frames=prev_frames,
        history_frames=history_frames,
        device=device,
    )
    context_rep = context_t.repeat_interleave(n_samples, dim=0)

    seq_rep = None
    if seq_feature is not None:
        seq_t = _as_float_tensor(seq_feature, device)
        if seq_t.ndim == 1:
            seq_t = seq_t.reshape(1, -1)
        else:
            seq_t = seq_t.reshape(seq_t.shape[0], -1)
        if seq_t.shape[0] == 1 and n_cond > 1:
            seq_t = seq_t.repeat(n_cond, 1)
        elif seq_t.shape[0] != n_cond:
            raise ValueError("seq_feature must broadcast to the conditioning batch size.")
        seq_rep = seq_t.repeat_interleave(n_samples, dim=0)

    ds = float(s_max) / float(n_steps)
    sqrt_ds = math.sqrt(ds)
    x = torch.randn((context_rep.shape[0], dim), dtype=torch.float32, device=device)

    mask_t = None
    if feature_mask is not None:
        mask_t = _as_float_tensor(feature_mask, device).reshape(1, dim)
        x = x * mask_t

    with torch.no_grad():
        for step in range(n_steps):
            s = max(float(s_max) - step * ds, 1e-6)
            st = torch.full((context_rep.shape[0],), s, dtype=torch.float32, device=device)
            pieces = [x, context_rep]
            if seq_rep is not None:
                pieces.append(seq_rep)
            inp = torch.cat(pieces, dim=-1)
            score = o_score.model(inp, st)
            score = torch.clamp(torch.nan_to_num(score, nan=0.0, posinf=10.0, neginf=-10.0), -10.0, 10.0)
            drift = torch.clamp(0.5 * x + score, -10.0, 10.0)
            x = x + drift * ds + torch.randn_like(x) * sqrt_ds
            x = torch.clamp(x, -2.0, 2.0)
            if mask_t is not None:
                x = x * mask_t

    x_np = x.detach().cpu().numpy()
    if n_cond == 1:
        return x_np.reshape(n_samples, dim)
    return x_np.reshape(n_cond, n_samples, dim)


def run_naive_paths(o_score, start_features, horizon_frames, s_max, n_steps, feature_mask=None, seq_feature=None):
    paths = np.zeros((len(start_features), horizon_frames + 1, start_features.shape[1]), dtype=np.float64)
    paths[:, 0] = start_features
    for t in range(horizon_frames):
        prev_frames = [paths[:, max(t - lag, 0)] for lag in range(1, getattr(o_score, "history_frames", 2))]
        paths[:, t + 1] = reverse_step(
            o_score,
            paths[:, t],
            n_samples=1,
            s_max=s_max,
            n_steps=n_steps,
            prev_frames=prev_frames,
            feature_mask=feature_mask,
            seq_feature=seq_feature,
            history_frames=getattr(o_score, "history_frames", 2),
        ).reshape(len(start_features), start_features.shape[1])
    return paths


def estimate_log_Z_from_chain(o_score, start_features, horizon_frames, endpoint_log_G, s_max, n_steps, n_samples, batch_size, rng, feature_mask=None, seq_feature=None):
    start_features = np.asarray(start_features, dtype=np.float64)
    log_rewards = np.zeros(n_samples, dtype=np.float64)
    for start in range(0, n_samples, batch_size):
        end = min(start + batch_size, n_samples)
        batch = end - start
        idx = rng.choice(len(start_features), size=batch, replace=True)
        paths = run_naive_paths(
            o_score,
            start_features[idx],
            horizon_frames=horizon_frames,
            s_max=s_max,
            n_steps=n_steps,
            feature_mask=feature_mask,
            seq_feature=seq_feature,
        )
        log_rewards[start:end] = endpoint_log_G(paths[:, -1], horizon_frames)
    return float(logsumexp(log_rewards) - np.log(n_samples))


def estimate_log_Z_from_rollouts(paths, horizon_frames, endpoint_log_G):
    paths = np.asarray(paths, dtype=np.float64)
    if paths.ndim != 3 or paths.shape[1] != horizon_frames + 1:
        raise ValueError("Expected rollout paths with shape (n_paths, horizon_frames + 1, dim).")
    log_rewards = endpoint_log_G(paths[:, -1], horizon_frames)
    return float(logsumexp(log_rewards) - np.log(len(log_rewards)))


def run_bootstrap_trial(o_score, start_features, horizon_frames, K, endpoint_log_G, s_max, n_steps, feature_mask=None, seq_feature=None):
    start_features = np.asarray(start_features, dtype=np.float64)
    if start_features.ndim == 1:
        start_features = np.tile(start_features, (K, 1))
    else:
        start_features = start_features.reshape(K, -1)
    traj = np.zeros((K, horizon_frames + 1, start_features.shape[1]), dtype=np.float64)
    traj[:, 0] = start_features
    ess_per_step = []
    log_Z = 0.0

    for t in range(1, horizon_frames + 1):
        prev_frames = [traj[:, max(t - 1 - lag, 0)] for lag in range(1, getattr(o_score, "history_frames", 2))]
        traj[:, t] = reverse_step(
            o_score,
            traj[:, t - 1],
            n_samples=1,
            s_max=s_max,
            n_steps=n_steps,
            prev_frames=prev_frames,
            feature_mask=feature_mask,
            seq_feature=seq_feature,
            history_frames=getattr(o_score, "history_frames", 2),
        ).reshape(K, start_features.shape[1])
        log_w = endpoint_log_G(traj[:, t], t) if t == horizon_frames else np.zeros(K, dtype=np.float64)
        log_Z += logsumexp(log_w) - np.log(K)
        ess_per_step.append(compute_ess(log_w))
        traj = traj[systematic_resample(log_w)]

    return {"paths": traj, "log_Z": float(log_Z), "ess_per_step": ess_per_step}


def sample_proposal_reference_windows(o_score, start_feature_pool, horizon_frames,
                                      total_paths, batch_K, s_max, n_steps, rng,
                                      feature_mask=None, seq_feature=None):
    total_paths = int(total_paths)
    batch_K = max(1, int(batch_K))
    dim = int(start_feature_pool.shape[1])
    windows = np.zeros((total_paths, horizon_frames + 1, dim), dtype=np.float32)
    written = 0
    while written < total_paths:
        cur = min(batch_K, total_paths - written)
        idx = rng.choice(len(start_feature_pool), size=cur, replace=True)
        rollout = run_naive_paths(
            o_score,
            start_feature_pool[idx],
            horizon_frames=horizon_frames,
            s_max=s_max,
            n_steps=n_steps,
            feature_mask=feature_mask,
            seq_feature=seq_feature,
        )
        windows[written:written + cur] = rollout[:cur]
        written += cur
    return windows


def run_take3_trial(o_score, twist_fn, start_features, horizon_frames, K, M, endpoint_log_G, s_max, n_steps, feature_mask=None, seq_feature=None):
    start_features = np.asarray(start_features, dtype=np.float64)
    if start_features.ndim == 1:
        start_features = np.tile(start_features, (K, 1))
    else:
        start_features = start_features.reshape(K, -1)
    traj = np.zeros((K, horizon_frames + 1, start_features.shape[1]), dtype=np.float64)
    traj[:, 0] = start_features
    log_psi_prev = np.asarray(twist_fn(start_features, 0), dtype=np.float64).reshape(K)
    log_Z = float(logsumexp(log_psi_prev) - np.log(K))
    ess_per_step = []

    for t in range(1, horizon_frames + 1):
        prev_frames = [traj[:, max(t - 1 - lag, 0)] for lag in range(1, getattr(o_score, "history_frames", 2))]
        proposals = reverse_step(
            o_score,
            traj[:, t - 1],
            n_samples=M,
            s_max=s_max,
            n_steps=n_steps,
            prev_frames=prev_frames,
            feature_mask=feature_mask,
            seq_feature=seq_feature,
            history_frames=getattr(o_score, "history_frames", 2),
        )
        log_G = endpoint_log_G(proposals.reshape(-1, start_features.shape[1]), t).reshape(K, M)
        if t < horizon_frames:
            log_twist = np.asarray(twist_fn(proposals.reshape(-1, start_features.shape[1]), t), dtype=np.float64).reshape(K, M)
        else:
            log_twist = np.zeros((K, M), dtype=np.float64)
        log_v = log_G + log_twist
        chosen, log_norm = sample_row_indices(log_v, n_draws=1)
        traj[:, t] = proposals[np.arange(K), chosen]
        log_weights = log_norm - np.log(M) - log_psi_prev
        log_psi_next = log_twist[np.arange(K), chosen] if t < horizon_frames else np.zeros(K, dtype=np.float64)

        log_Z += logsumexp(log_weights) - np.log(K)
        ess_per_step.append(compute_ess(log_weights))
        resampled = systematic_resample(log_weights)
        traj = traj[resampled]
        if t < horizon_frames:
            log_psi_prev = log_psi_next[resampled]

    return {"paths": traj, "log_Z": float(log_Z), "ess_per_step": ess_per_step}


def evaluate_tps_task_for_peptide(
    peptide_name,
    features,
    feature_mask,
    state_model,
    o_score,
    seq_feature,
    args,
    start_state,
    end_state,
    powers,
    pair_selection,
    seed_offset,
    mdgen_paths_dir=None,
):
    rng = np.random.default_rng(seed_offset)
    reference_state_paths, reference_valid, powers = sample_conditioned_state_paths(
        state_model["transition_matrix"],
        start_state,
        end_state,
        args.path_length,
        args.reference_paths,
        rng,
    )
    reference_state_paths = reference_state_paths[reference_valid]
    if len(reference_state_paths) == 0:
        raise ValueError("Conditioned MSM sampler produced no valid reference paths.")

    windows, _ = select_start_state_windows(
        features,
        state_model["labels"],
        start_state,
        horizon_frames=args.horizon_frames,
        stride=args.window_stride,
        max_windows=args.max_ref_windows,
        rng=rng,
    )
    if len(windows) == 0:
        raise ValueError(f"No windows starting from state {start_state}.")
    all_start_windows, _ = select_start_state_windows(
        features,
        state_model["labels"],
        start_state,
        horizon_frames=args.horizon_frames,
        stride=args.window_stride,
        max_windows=None,
        rng=rng,
    )

    endpoint_log_G = endpoint_log_reward_factory(
        state_model["tica_model"],
        state_model["state_centers"],
        end_state,
        horizon_frames=args.horizon_frames,
        lam=args.reward_lambda,
        mode="soft_state",
    )
    future_targets_oracle = build_future_reward_targets(windows, args.horizon_frames, endpoint_log_G)
    start_feature_pool = features[state_model["labels"] == start_state]
    empirical_log_Z = float(
        logsumexp(endpoint_log_G(all_start_windows[:, -1], args.horizon_frames)) - np.log(len(all_start_windows))
    )

    twist_oracle = None
    oracle_twist_time = None
    if not args.skip_oracle_twist:
        print(f"Training Take 3 oracle twist ({pair_selection['mode']})...")
        t0 = time.time()
        twist_oracle_model, _ = train_positive_twist_kl(
            windows,
            future_targets_oracle,
            dim=features.shape[1],
            T=args.horizon_frames,
            n_epochs=args.twist_epochs,
            lr=args.twist_lr,
            hidden_dim=args.hidden_dim,
            n_layers=max(args.n_layers - 1, 2),
            device=args.device,
        )
        twist_oracle = PositiveNNTwist(twist_oracle_model, dim=features.shape[1], device=args.device)
        oracle_twist_time = time.time() - t0
        print(f"  Oracle twist training time: {oracle_twist_time:.1f}s")

    print(f"Generating unconditional learned-proposal self-reference windows ({pair_selection['mode']})...")
    self_ref_rng = np.random.default_rng(seed_offset + 5000)
    self_ref_windows = sample_proposal_reference_windows(
        o_score,
        start_feature_pool,
        horizon_frames=args.horizon_frames,
        total_paths=max(1, args.self_ref_windows),
        batch_K=max(1, args.self_ref_batch_size),
        s_max=args.S_max,
        n_steps=args.n_diff_steps,
        rng=self_ref_rng,
        feature_mask=feature_mask,
        seq_feature=seq_feature,
    )
    self_future_targets = build_future_reward_targets(self_ref_windows, args.horizon_frames, endpoint_log_G)

    print(f"Training Take 3 self-trained twist ({pair_selection['mode']})...")
    t0 = time.time()
    twist_self_model, _ = train_positive_twist_kl(
        self_ref_windows,
        self_future_targets,
        dim=features.shape[1],
        T=args.horizon_frames,
        n_epochs=args.twist_epochs,
        lr=args.twist_lr,
        hidden_dim=args.hidden_dim,
        n_layers=max(args.n_layers - 1, 2),
        device=args.device,
    )
    twist_self = PositiveNNTwist(twist_self_model, dim=features.shape[1], device=args.device)
    self_twist_time = time.time() - t0
    print(f"  Self twist training time: {self_twist_time:.1f}s")

    learned_log_Z = estimate_log_Z_from_rollouts(
        self_ref_windows,
        horizon_frames=args.horizon_frames,
        endpoint_log_G=endpoint_log_G,
    )

    num_paths = args.K * args.n_trials
    start_features, _ = sample_start_features(
        features,
        state_model["labels"],
        start_state,
        num_paths,
        rng,
    )

    print(f"Generating NaiveDiffusion paths ({pair_selection['mode']})...")
    naive_paths = run_naive_paths(
        o_score,
        start_features,
        horizon_frames=args.horizon_frames,
        s_max=args.S_max,
        n_steps=args.n_diff_steps,
        feature_mask=feature_mask,
        seq_feature=seq_feature,
    )
    naive_state_paths = discretize_feature_paths(
        naive_paths,
        state_model["tica_model"],
        state_model["state_centers"],
        lag_frames=args.lag_frames,
        path_length=args.path_length,
    )
    naive_trial_log_z = []
    for trial in range(args.n_trials):
        trial_paths = naive_paths[trial * args.K:(trial + 1) * args.K]
        naive_trial_log_z.append(
            estimate_log_Z_from_rollouts(
                trial_paths,
                horizon_frames=args.horizon_frames,
                endpoint_log_G=endpoint_log_G,
            )
        )

    bootstrap_trials = []
    bootstrap_paths = []
    take3_oracle_trials = []
    take3_oracle_paths = []
    take3_self_trials = []
    take3_self_paths = []

    for trial in range(args.n_trials):
        start_batch = start_features[trial * args.K:(trial + 1) * args.K]
        bootstrap_out = run_bootstrap_trial(
            o_score,
            start_batch,
            horizon_frames=args.horizon_frames,
            K=args.K,
            endpoint_log_G=endpoint_log_G,
            s_max=args.S_max,
            n_steps=args.n_diff_steps,
            feature_mask=feature_mask,
            seq_feature=seq_feature,
        )
        bootstrap_trials.append(bootstrap_out)
        bootstrap_paths.append(bootstrap_out["paths"])

        if twist_oracle is not None:
            take3_oracle_out = run_take3_trial(
                o_score,
                twist_oracle,
                start_batch,
                horizon_frames=args.horizon_frames,
                K=args.K,
                M=args.M,
                endpoint_log_G=endpoint_log_G,
                s_max=args.S_max,
                n_steps=args.n_diff_steps,
                feature_mask=feature_mask,
                seq_feature=seq_feature,
            )
            take3_oracle_trials.append(take3_oracle_out)
            take3_oracle_paths.append(take3_oracle_out["paths"])

        take3_self_out = run_take3_trial(
            o_score,
            twist_self,
            start_batch,
            horizon_frames=args.horizon_frames,
            K=args.K,
            M=args.M,
            endpoint_log_G=endpoint_log_G,
            s_max=args.S_max,
            n_steps=args.n_diff_steps,
            feature_mask=feature_mask,
            seq_feature=seq_feature,
        )
        take3_self_trials.append(take3_self_out)
        take3_self_paths.append(take3_self_out["paths"])

    bootstrap_paths = np.concatenate(bootstrap_paths, axis=0)
    take3_self_paths = np.concatenate(take3_self_paths, axis=0)
    has_oracle_paths = len(take3_oracle_paths) > 0
    take3_oracle_paths_arr = None
    if has_oracle_paths:
        take3_oracle_paths_arr = np.concatenate(take3_oracle_paths, axis=0)

    bootstrap_state_paths = discretize_feature_paths(
        bootstrap_paths,
        state_model["tica_model"],
        state_model["state_centers"],
        lag_frames=args.lag_frames,
        path_length=args.path_length,
    )
    take3_self_state_paths = discretize_feature_paths(
        take3_self_paths,
        state_model["tica_model"],
        state_model["state_centers"],
        lag_frames=args.lag_frames,
        path_length=args.path_length,
    )
    take3_oracle_state_paths = None
    if has_oracle_paths:
        take3_oracle_state_paths = discretize_feature_paths(
            take3_oracle_paths_arr,
            state_model["tica_model"],
            state_model["state_centers"],
            lag_frames=args.lag_frames,
            path_length=args.path_length,
        )

    task_result = {
        "pair_selection": pair_selection,
        "start_state": int(start_state),
        "end_state": int(end_state),
        "reference_flux": float(state_model["stationary"][start_state] * state_model["transition_matrix"][start_state, end_state]),
        "reference_metrics": {
            "num_paths": int(len(reference_state_paths)),
            "valid_path_rate": float(np.mean(reference_valid)),
        },
        "ground_truth": {
            "empirical_log_Z_from_reference_windows": empirical_log_Z,
            "learned_proposal_log_Z": learned_log_Z,
        },
        "twist_training": {
            "oracle_ref_windows": int(len(windows)),
            "oracle_training_time_sec": None if oracle_twist_time is None else float(oracle_twist_time),
            "self_ref_windows": int(len(self_ref_windows)),
            "self_training_time_sec": float(self_twist_time),
            "self_ref_source": "unconditional_learned_proposal_rollouts",
        },
        "methods": {
            "NaiveDiffusion": {
                "num_paths": int(len(naive_paths)),
                "log_Z": mean_std(naive_trial_log_z),
                "metrics": compute_tps_metrics(
                    reference_state_paths,
                    naive_state_paths,
                    state_model["transition_matrix"],
                    powers,
                    start_state=start_state,
                    end_state=end_state,
                ),
            },
            "Bootstrap": {
                "num_paths": int(len(bootstrap_paths)),
                "log_Z": mean_std([x["log_Z"] for x in bootstrap_trials]),
                "ess": mean_std([np.mean(x["ess_per_step"]) for x in bootstrap_trials]),
                "metrics": compute_tps_metrics(
                    reference_state_paths,
                    bootstrap_state_paths,
                    state_model["transition_matrix"],
                    powers,
                    start_state=start_state,
                    end_state=end_state,
                ),
            },
            "Take3-SelfTwist": {
                "num_paths": int(len(take3_self_paths)),
                "log_Z": mean_std([x["log_Z"] for x in take3_self_trials]),
                "ess": mean_std([np.mean(x["ess_per_step"]) for x in take3_self_trials]),
                "metrics": compute_tps_metrics(
                    reference_state_paths,
                    take3_self_state_paths,
                    state_model["transition_matrix"],
                    powers,
                    start_state=start_state,
                    end_state=end_state,
                ),
            },
        },
    }
    if take3_oracle_trials:
        task_result["methods"]["Take3-OracleTwist"] = {
            "num_paths": int(len(take3_oracle_paths_arr)),
            "log_Z": mean_std([x["log_Z"] for x in take3_oracle_trials]),
            "ess": mean_std([np.mean(x["ess_per_step"]) for x in take3_oracle_trials]),
            "metrics": compute_tps_metrics(
                reference_state_paths,
                take3_oracle_state_paths,
                state_model["transition_matrix"],
                powers,
                start_state=start_state,
                end_state=end_state,
            ),
        }

    external = maybe_eval_external_mdgen(
        path_dir=mdgen_paths_dir,
        peptide_name=peptide_name,
        tica_model=state_model["tica_model"],
        state_centers=state_model["state_centers"],
        path_length=args.path_length,
        reference_paths=reference_state_paths,
        T_ref=state_model["transition_matrix"],
        powers=powers,
    )
    if external is not None:
        task_result["methods"]["MDGenExternal"] = external

    return task_result


def maybe_eval_external_mdgen(path_dir, peptide_name, tica_model, state_centers, path_length, reference_paths, T_ref, powers):
    if path_dir is None:
        return None
    for suffix in (".npz", "_paths.npz", "_samples.npz"):
        candidate = os.path.join(path_dir, peptide_name + suffix)
        if os.path.exists(candidate):
            payload = load_mdgen_like_path_file(candidate)
            if "state_paths" in payload:
                state_paths = payload["state_paths"]
            else:
                features = payload["features"]
                if features.ndim == 2:
                    return None
                state_paths = discretize_feature_paths(features, tica_model, state_centers, lag_frames=1, path_length=path_length)
            return {
                "file": candidate,
                "metrics": compute_tps_metrics(
                    reference_paths=reference_paths,
                    sample_paths=state_paths,
                    T_ref=T_ref,
                    powers=powers,
                    start_state=int(reference_paths[0, 0]),
                    end_state=int(reference_paths[0, -1]),
                ),
            }
    return None


